const MESSAGES: Record<Lang, Messages> = { en, vi };

/** Current language, its UI strings, and a translator for data text. */
export function useI18n() {
  const lang = langStore.useValue();
  return { lang, t: MESSAGES[lang], tr: (text: Text) => tr(text, lang) };
}
